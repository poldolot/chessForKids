/// Resolves a match speech key such as `match.check` to its localized text.
String matchLine(AppLocalizations l10n, String key) => switch (key) {
  'match.title' => l10n.matchTitle,
  'match.intro' => l10n.matchIntro,
  'match.introBlack' => l10n.matchIntroBlack,
  'match.yourMove' => l10n.yourMove,
  'match.thinking' => l10n.matchThinking,
  'match.check' => l10n.check,
  'match.checkByYou' => l10n.matchCheckByYou,
  'match.hint' => l10n.matchHint,
  'match.undo' => l10n.undo,
  'match.resign' => l10n.matchResign,
  'match.resignQuestion' => l10n.matchResignQuestion,
  'match.yes' => l10n.matchYes,
  'match.no' => l10n.matchNo,
  'match.won' => l10n.matchWon,
  'match.lost' => l10n.matchLost,
  'match.resigned' => l10n.matchResigned,
  'match.stalemate' => l10n.stalemate,
  'match.draw' => l10n.draw,
  'match.again' => l10n.matchAgain,
  'match.back' => l10n.matchBack,
  'match.badgeFirstMatch' => l10n.matchBadgeFirstMatch,
  'match.badgeFirstWin' => l10n.matchBadgeFirstWin,
  'match.badgePersistent' => l10n.matchBadgePersistent,
  'match.badgeCollector' => l10n.gamesCommonBadgeCollector,
  _ => throw ArgumentError.value(key, 'key', 'Unknown match line'),
};
